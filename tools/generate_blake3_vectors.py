#!/usr/bin/env python3
"""Copy pinned official BLAKE3 answers into a C++ header; --check is the default.

This script never calculates a BLAKE3 answer or invokes the candidate library.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "upstream/blake3/test_vectors/test_vectors.json"
DESTINATION = ROOT / "native/fixtures/blake3_vectors.hpp"
PIN = "93a431c78a52d7ccf0f366f106467f5070e6075e"
SOURCE_SHA256 = "dcb91ea8accc77e6d6e632af7cdc1a99a9f3ae78cf648da595c7d064db32f624"
MODES = ("hash", "keyed_hash", "derive_key")


def generate() -> bytes:
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Official BLAKE3 vectors differ from the pinned source; inspect the dependency")
    data = json.loads(raw)
    if len(data["cases"]) != 35 or len(data["key"].encode("ascii")) != 32:
        raise ValueError("Unexpected official vector schema")
    data["context_string"].encode("ascii")
    lines = [
        "// Generated by tools/generate_blake3_vectors.py; do not edit expected answers.",
        "// Official BLAKE3 test data; license texts are retained in upstream/blake3.",
        f"// Source: BLAKE3-team/BLAKE3@{PIN}/test_vectors/test_vectors.json",
        f"// Source SHA-256: {SOURCE_SHA256}",
        "#pragma once", "", "#include <array>", "#include <cstddef>",
        "#include <string_view>", "", "namespace neuro::blake3_vectors {", "",
        'inline constexpr char version[] = "1.8.5";',
        f"inline constexpr char source_commit[] = {json.dumps(PIN)};",
        f"inline constexpr char key[] = {json.dumps(data['key'])};",
        f"inline constexpr char context[] = {json.dumps(data['context_string'])};",
        "inline constexpr std::size_t output_bytes = 131;", "",
        "struct Vector {", "    std::size_t input_length;",
        "    std::array<std::string_view, 3> output_hex;", "};", "",
        "inline constexpr std::array<Vector, 35> vectors = {{",
    ]
    for case in data["cases"]:
        length = case["input_len"]
        if type(length) is not int or not 0 <= length <= 102400:
            raise ValueError("Unexpected official input length")
        lines.append(f"    {{{length}, {{{{")
        for mode in MODES:
            value = case[mode]
            if len(value) != 262 or any(c not in "0123456789abcdef" for c in value):
                raise ValueError("Unexpected official output encoding")
            chunks = [value[i:i + 64] for i in range(0, len(value), 64)]
            for index, chunk in enumerate(chunks):
                lines.append("        " + json.dumps(chunk) + ("," if index == len(chunks) - 1 else ""))
        lines.append("    }}},")
    lines.extend(["}};", "", "} // namespace neuro::blake3_vectors", ""])
    return "\n".join(lines).encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Check the existing header without writing (default)")
    mode.add_argument("--write", action="store_true", help="Explicitly copy official answers into the header")
    args = parser.parse_args(argv)
    result = {"schema": "neuro.blake3_fixture_check.v1", "mode": "write" if args.write else "check",
              "candidate_hash_calculations": False, "source_commit": PIN}
    try:
        expected = generate()
        if args.write:
            DESTINATION.parent.mkdir(parents=True, exist_ok=True)
            DESTINATION.write_bytes(expected)
        elif not DESTINATION.exists() or DESTINATION.read_bytes() != expected:
            raise ValueError("BLAKE3 fixture header is missing or differs from the official answers")
        result.update(status="PASS", cases=35, modes_per_case=3,
                      header_sha256=hashlib.sha256(expected).hexdigest())
    except (OSError, ValueError, KeyError, TypeError) as error:
        result.update(status="FAIL", error=str(error))
    print(json.dumps(result, sort_keys=True))
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
